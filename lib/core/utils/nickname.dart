/// 화면에서 부를 이름 — 세 글자 한국 이름은 성을 뗀다.
///
/// 서버가 주는 이름은 가입 경로에 따라 갈린다. 카카오는 대개 성까지 온다
/// (`이예빈`). 그대로 부르면 `이예빈님, 어디로 떠나볼까요?`가 되는데,
/// 사람을 성까지 붙여 부르는 자리가 아니다 — 친구가 부르듯 `예빈님`이 맞다.
///
/// **세 글자일 때만 뗀다.** 두 글자는 이미 이름만 남았거나(`민수`) 성을 떼면
/// 한 글자가 되어 부를 수 없고, 네 글자 이상은 복성(`남궁예빈`)이거나 한국
/// 이름이 아닐(`크리스티나`) 수 있어 어디를 잘라야 할지 알 수 없다.
///
/// 한글이 아닌 이름은 손대지 않는다 — `Alex`에서 `lex`가 되면 안 된다.
String displayName(String name) {
  final trimmed = name.trim();
  if (trimmed.length != 3) return trimmed;
  // 한글 음절(가~힣)로만 이뤄진 이름에만 적용한다
  if (!RegExp(r'^[가-힣]{3}$').hasMatch(trimmed)) return trimmed;
  return trimmed.substring(1);
}
